#!/usr/bin/env python3
"""Deterministic graph generator for tests/gc-torture/src/datalog_lite.extc.

Usage: gen_graph.py [edges] [queries] [nodes] [seed]

Emits to stdout exactly the input format the program documents:
  n <nodes>
  e <src> <dst>      x edges
  q <node>            x queries

Deterministic: same arguments => byte-identical output (the golden files and the
cross-language comparison depend on it). The edge mix is 70% uniform, 20%
preferential (to a hub set) and 10% cycle-closing, so reachability is neither
trivially flat nor a single giant blob.
"""
import random
import sys

def main():
    edges = int(sys.argv[1]) if len(sys.argv) > 1 else 200000
    queries = int(sys.argv[2]) if len(sys.argv) > 2 else 32
    nodes = int(sys.argv[3]) if len(sys.argv) > 3 else 50000
    seed = int(sys.argv[4]) if len(sys.argv) > 4 else 7
    rng = random.Random(seed)
    hubs = [rng.randrange(nodes) for _ in range(max(1, nodes // 500))]
    out = []
    out.append("# generated by gen_graph.py edges=%d queries=%d nodes=%d seed=%d" % (edges, queries, nodes, seed))
    out.append("n %d" % nodes)
    for i in range(edges):
        r = rng.random()
        a = rng.randrange(nodes)
        if r < 0.70:
            b = rng.randrange(nodes)
        elif r < 0.90:
            b = hubs[rng.randrange(len(hubs))]
        else:
            b = (a + 1) % nodes
        out.append("e %d %d" % (a, b))
    for _ in range(queries):
        out.append("q %d" % rng.randrange(nodes))
    sys.stdout.write("\n".join(out) + "\n")

if __name__ == "__main__":
    main()